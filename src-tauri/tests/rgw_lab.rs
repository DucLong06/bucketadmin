//! Integration tests against a real RGW (the lab: Ceph squid on 127.0.0.1:7480).
//! They run only when RGW_ACCESS_KEY and RGW_SECRET_KEY are set; otherwise each
//! test prints "SKIPPED" and passes, so CI without a cluster stays green.
//!
//!   RGW_ACCESS_KEY=... RGW_SECRET_KEY=... cargo test --test rgw_lab -- --nocapture

use bucketadmin_lib::rgw_admin::{
    Credentials, QuotaType, ReqwestClient, RgwAdmin, RgwError, UserModify,
};

fn endpoint() -> String {
    std::env::var("RGW_ENDPOINT").unwrap_or_else(|_| "http://127.0.0.1:7480".into())
}

fn lab() -> Option<RgwAdmin> {
    let (Ok(access_key), Ok(secret_key)) = (
        std::env::var("RGW_ACCESS_KEY"),
        std::env::var("RGW_SECRET_KEY"),
    ) else {
        eprintln!("SKIPPED: RGW_ACCESS_KEY / RGW_SECRET_KEY not set");
        return None;
    };
    let creds = Credentials {
        access_key,
        secret_key,
    };
    Some(RgwAdmin::new(&endpoint(), creds, ReqwestClient::new().unwrap()).unwrap())
}

#[tokio::test]
async fn get_info_returns_cluster_id() {
    let Some(admin) = lab() else { return };
    let info = admin.get_info().await.expect("GET /admin/info");
    println!("get_info -> 200 {info:?}");
    assert!(!info.cluster_id.is_empty());
}

#[tokio::test]
async fn list_users_returns_users() {
    let Some(admin) = lab() else { return };
    let users = admin.list_users().await.expect("GET /admin/metadata/user");
    println!("list_users -> 200 {users:?}");
    assert!(!users.is_empty());
}

#[tokio::test]
async fn wrong_secret_is_reported_as_signature_mismatch() {
    let Ok(access_key) = std::env::var("RGW_ACCESS_KEY") else {
        eprintln!("SKIPPED: RGW_ACCESS_KEY not set");
        return;
    };
    let creds = Credentials {
        access_key,
        secret_key: "definitely-not-the-secret".into(),
    };
    let admin = RgwAdmin::new(&endpoint(), creds, ReqwestClient::new().unwrap()).unwrap();
    let err = admin.get_info().await.unwrap_err();
    println!("wrong secret -> {err}");
    assert_eq!(err, RgwError::SignatureDoesNotMatch);
}

/// Exercises every write call on a throw-away user, then removes it.
#[tokio::test]
async fn user_lifecycle() {
    let Some(admin) = lab() else { return };
    let uid = "ba-m0-itest";
    let _ = admin.delete_user(uid, true).await; // leftover from an aborted run

    let user = admin
        .create_user(uid, "M0 integration test", None, None, None)
        .await
        .expect("create_user");
    assert_eq!(user.user_id, uid);
    assert_eq!(user.keys.len(), 1, "a key pair is generated by default");
    assert_eq!(
        admin
            .create_user(uid, "dup", None, None, None)
            .await
            .unwrap_err(),
        RgwError::UserAlreadyExists
    );

    let caps = admin.add_caps(uid, "usage=read").await.expect("add_caps");
    println!("add_caps -> {caps:?}");
    assert!(caps
        .iter()
        .any(|c| c.cap_type == "usage" && c.perm == "read"));

    admin
        .set_quota(uid, QuotaType::User, true, 1024, -1)
        .await
        .expect("set_quota");
    let quota = admin
        .get_quota(uid, QuotaType::User)
        .await
        .expect("get_quota");
    println!("get_quota -> {quota:?}");
    assert!(quota.enabled);
    assert_eq!(quota.max_size_kb, 1024);
    assert!(quota.max_objects < 0);

    let changes = UserModify {
        display_name: Some("renamed".into()),
        suspended: Some(true),
        ..Default::default()
    };
    let modified = admin.modify_user(uid, &changes).await.expect("modify_user");
    assert_eq!(modified.display_name, "renamed");
    assert_eq!(modified.suspended, 1);

    let fetched = admin.get_user(uid).await.expect("get_user");
    assert_eq!(fetched.display_name, "renamed");
    assert_eq!(fetched.caps.len(), 1);

    let usage = admin.get_usage(Some(uid)).await.expect("get_usage");
    println!("get_usage -> {usage:?}");

    let caps = admin
        .remove_caps(uid, "usage=read")
        .await
        .expect("remove_caps");
    assert!(caps.is_empty());

    admin.delete_user(uid, false).await.expect("delete_user");
    assert_eq!(admin.get_user(uid).await.unwrap_err(), RgwError::NoSuchUser);
}

/// M1 flow through the audited operations layer (what the Tauri commands call):
/// create user -> add caps -> set quota -> usage -> keys -> suspend -> delete.
#[tokio::test]
async fn m1_flow_through_ops_is_audited() {
    use bucketadmin_lib::{audit::Audit, ops::Ops};
    let Some(admin) = lab() else { return };
    let uid = "ba-m1-itest";
    let _ = admin.delete_user(uid, true).await; // leftover from an aborted run
    let audit = Audit::in_memory().unwrap();
    let ops = Ops {
        admin,
        audit: &audit,
        cluster_id: "lab".into(),
    };

    let created = ops
        .create_user(uid, "M1 flow", &Some("m1@example.com".into()), &None, &None)
        .await
        .expect("create_user");
    let first = created.keys[0].clone();
    assert!(!first.secret_key.is_empty(), "secret is returned on create");
    let listed = ops.list_users().await.expect("list_users");
    let row = listed
        .iter()
        .find(|u| u.user_id == uid)
        .expect("new user is listed");
    assert_eq!(row.keys[0].access_key, first.access_key);
    assert!(listed
        .iter()
        .all(|u| u.keys.iter().all(|k| k.secret_key.is_empty())));
    println!("list_users -> {} users, secrets stripped", listed.len());

    // The space is the case the reference Python script could not sign.
    let caps = ops
        .add_cap(uid, "usage=read, write")
        .await
        .expect("add_cap");
    println!("add_cap usage=read, write -> {caps:?}");
    assert_eq!(
        (caps[0].cap_type.as_str(), caps[0].perm.as_str()),
        ("usage", "*")
    );
    ops.add_cap(uid, "buckets=read").await.expect("add_cap 2");
    assert!(ops
        .add_cap(uid, "zones=read")
        .await
        .unwrap_err()
        .starts_with("InvalidCapability"));
    let caps = ops
        .remove_cap(uid, "usage=write")
        .await
        .expect("remove_cap");
    println!("remove_cap usage=write -> {caps:?}");

    ops.set_quota(uid, QuotaType::User, true, 2048, 100)
        .await
        .expect("set user quota");
    ops.set_quota(uid, QuotaType::Bucket, true, -1, 5)
        .await
        .expect("set bucket quota");
    let quotas = ops.get_quotas(uid).await.expect("get_quotas");
    println!("get_quotas -> {quotas:?}");
    assert_eq!(
        (quotas.user.max_size_kb, quotas.user.max_objects),
        (2048, 100)
    );
    assert!(quotas.bucket.enabled && quotas.bucket.max_size < 0 && quotas.bucket.max_objects == 5);

    let usage = ops.get_usage(uid).await.expect("get_usage");
    println!("get_usage -> {usage:?}");

    let second = ops.create_key(uid).await.expect("create_key");
    assert_ne!(second.access_key, first.access_key);
    let rotated = ops
        .rotate_key(uid, &first.access_key)
        .await
        .expect("rotate_key");
    assert_eq!(rotated.remove_error, None);
    ops.remove_key(uid, &second.access_key)
        .await
        .expect("remove_key");
    let user = ops.get_user(uid).await.expect("get_user");
    let left: Vec<&str> = user.keys.iter().map(|k| k.access_key.as_str()).collect();
    assert_eq!(
        left,
        [rotated.key.access_key.as_str()],
        "only the rotated key remains"
    );

    let modified = ops
        .modify_user(uid, "M1 renamed", "")
        .await
        .expect("modify_user");
    assert_eq!(
        (modified.display_name.as_str(), modified.email.as_str()),
        ("M1 renamed", "")
    );
    assert_eq!(
        ops.set_suspended(uid, true)
            .await
            .expect("suspend")
            .suspended,
        1
    );
    assert_eq!(
        ops.set_suspended(uid, false)
            .await
            .expect("enable")
            .suspended,
        0
    );
    ops.delete_user(uid).await.expect("delete_user");
    assert!(ops
        .get_user(uid)
        .await
        .unwrap_err()
        .starts_with("NoSuchUser"));

    let mut log = audit.recent(None, None).unwrap();
    log.reverse();
    let actions: Vec<String> = log
        .iter()
        .map(|e| format!("{}{}", e.action, if e.ok { "" } else { "!" }))
        .collect();
    println!("audit -> {actions:?}");
    assert_eq!(
        actions,
        [
            "user.create",
            "caps.add",
            "caps.add",
            "caps.add!",
            "caps.remove",
            "quota.set",
            "quota.set",
            "key.create",
            "key.create",
            "key.remove",
            "key.remove",
            "user.modify",
            "user.suspend",
            "user.enable",
            "user.delete"
        ]
    );
    let dump = format!("{log:?}");
    for secret in [
        &first.secret_key,
        &second.secret_key,
        &rotated.key.secret_key,
    ] {
        assert!(
            !dump.contains(secret.as_str()),
            "a secret key reached the audit log"
        );
    }
}
