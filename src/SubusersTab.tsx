import { type FormEvent, useState } from "react";
import { Button, Chip, Paper, Stack, TextField, Typography } from "@mui/material";
import { invoke, type KeyPair, type Subuser } from "./api";
import { ConfirmDialog, ErrorAlert, SecretDialog, useAction } from "./ui";
import type { UserTabProps } from "./UserDrawer";

type NewSubuser = { subusers: Subuser[]; swift_key: KeyPair | null };

// Values of RGW's `access` parameter; RGW reports them back as read / write / read-write / full-control.
const ACCESS = [
  { value: "read", label: "read" },
  { value: "write", label: "write" },
  { value: "readwrite", label: "read + write" },
  { value: "full", label: "full control" },
];

/** "uid:name" -> "name" (a tenanted uid contains "$" but never ":"). */
const shortName = (id: string) => id.slice(id.lastIndexOf(":") + 1);

export default function SubusersTab({ clusterId, uid, user, refresh }: UserTabProps) {
  const [name, setName] = useState("");
  const [access, setAccess] = useState(ACCESS[0].value);
  const [fresh, setFresh] = useState<KeyPair[] | null>(null);
  const [removing, setRemoving] = useState<string | null>(null);
  const { busy, error, run, setError } = useAction();

  const subusers = user.subusers ?? [];
  const nameError = !name
    ? null
    : !/^[A-Za-z0-9_-]+$/.test(name)
      ? "Tên subuser chỉ gồm chữ, số, dấu - và _."
      : subusers.some((s) => shortName(s.id) === name)
        ? "Subuser này đã tồn tại."
        : null;

  async function create(e: FormEvent) {
    e.preventDefault();
    const created = await run(() => invoke<NewSubuser>("subuser_create", { clusterId, uid, subuser: name, access }));
    if (created) {
      setName("");
      // The Swift secret is generated by RGW and shown once, like an S3 secret key.
      setFresh(created.swift_key ? [{ ...created.swift_key, access_key: created.swift_key.user }] : []);
      await refresh();
    }
  }

  async function remove() {
    if (!removing) return;
    const done = await run(() => invoke("subuser_remove", { clusterId, uid, subuser: removing }).then(() => true));
    if (done) {
      setRemoving(null);
      await refresh();
    }
  }

  return (
    <Stack spacing={3}>
      <Stack spacing={1}>
        <Typography variant="subtitle1" component="h3">
          Subuser (Swift)
        </Typography>
        {subusers.length === 0 && <Typography color="text.secondary">User chưa có subuser nào.</Typography>}
        <Stack spacing={1} component="ul" sx={{ listStyle: "none", p: 0, m: 0 }}>
          {subusers.map((s) => (
            <Paper key={s.id} component="li" variant="outlined" sx={{ px: 2, py: 1 }}>
              <Stack direction="row" spacing={1} sx={{ alignItems: "center" }}>
                <Typography sx={{ flexGrow: 1, fontFamily: "monospace" }}>{s.id}</Typography>
                <Chip size="small" variant="outlined" label={s.permissions || "không có quyền"} />
                <Button
                  size="small"
                  color="error"
                  onClick={() => setRemoving(shortName(s.id))}
                  aria-label={`Xoá subuser ${s.id}`}
                >
                  Xoá
                </Button>
              </Stack>
            </Paper>
          ))}
        </Stack>
      </Stack>

      <Stack component="form" onSubmit={create} spacing={1}>
        <Typography variant="subtitle1" component="h3">
          Tạo subuser
        </Typography>
        <Stack direction="row" spacing={1} sx={{ alignItems: "flex-start" }}>
          <TextField
            label="Tên subuser"
            value={name}
            onChange={(e) => setName(e.target.value.trim())}
            size="small"
            sx={{ minWidth: 240 }}
            error={!!nameError}
            helperText={nameError ?? `Sẽ thành ${uid}:${name || "<tên>"}`}
          />
          <TextField
            select
            label="Quyền"
            value={access}
            onChange={(e) => setAccess(e.target.value)}
            size="small"
            sx={{ minWidth: 160 }}
            slotProps={{ select: { native: true } }}
          >
            {ACCESS.map((a) => (
              <option key={a.value} value={a.value}>
                {a.label}
              </option>
            ))}
          </TextField>
          <Button type="submit" variant="contained" disabled={busy || !name || !!nameError}>
            Tạo subuser
          </Button>
        </Stack>
      </Stack>
      {removing === null && <ErrorAlert error={error} />}

      <ConfirmDialog
        open={removing !== null}
        title="Xoá subuser?"
        text={`Subuser ${uid}:${removing} và Swift key của nó sẽ bị xoá.`}
        confirmLabel="Xoá subuser"
        busy={busy}
        error={error}
        onConfirm={remove}
        onClose={() => {
          setRemoving(null);
          setError(null);
        }}
      />
      <SecretDialog keys={fresh} accessLabel="Swift user" onClose={() => setFresh(null)} />
    </Stack>
  );
}
